package com.ccmobile.passwordmanager.ui.generator

import androidx.compose.foundation.layout.Arrangement
import androidx.compose.foundation.layout.Column
import androidx.compose.foundation.layout.Row
import androidx.compose.foundation.layout.fillMaxWidth
import androidx.compose.foundation.layout.padding
import androidx.compose.material3.AlertDialog
import androidx.compose.material3.MaterialTheme
import androidx.compose.material3.Slider
import androidx.compose.material3.Switch
import androidx.compose.material3.Text
import androidx.compose.material3.TextButton
import androidx.compose.runtime.Composable
import androidx.compose.runtime.getValue
import androidx.compose.runtime.mutableStateOf
import androidx.compose.runtime.remember
import androidx.compose.runtime.setValue
import androidx.compose.ui.Alignment
import androidx.compose.ui.Modifier
import androidx.compose.ui.text.font.FontFamily
import androidx.compose.ui.unit.dp
import com.ccmobile.passwordmanager.util.PasswordGenerator
import com.ccmobile.passwordmanager.util.PasswordOptions

@Composable
fun PasswordGeneratorDialog(
    onAccept: (String) -> Unit,
    onDismiss: () -> Unit,
) {
    var length by remember { mutableStateOf(16f) }
    var useUpper by remember { mutableStateOf(true) }
    var useLower by remember { mutableStateOf(true) }
    var useDigits by remember { mutableStateOf(true) }
    var useSymbols by remember { mutableStateOf(true) }
    var avoidAmbiguous by remember { mutableStateOf(false) }

    fun options() = PasswordOptions(
        length = length.toInt(),
        useUppercase = useUpper,
        useLowercase = useLower,
        useDigits = useDigits,
        useSymbols = useSymbols,
        avoidAmbiguous = avoidAmbiguous,
    )

    fun safeGenerate(): String = try {
        PasswordGenerator.generate(options())
    } catch (e: IllegalArgumentException) {
        ""
    }

    var generated by remember { mutableStateOf(safeGenerate()) }

    // Regenerate whenever any option changes.
    fun regenerate() { generated = safeGenerate() }

    AlertDialog(
        onDismissRequest = onDismiss,
        title = { Text("Générer un mot de passe") },
        text = {
            Column(verticalArrangement = Arrangement.spacedBy(4.dp)) {
                Text(
                    text = generated.ifEmpty { "Sélectionnez au moins un type" },
                    style = MaterialTheme.typography.titleMedium,
                    fontFamily = FontFamily.Monospace,
                    modifier = Modifier.fillMaxWidth().padding(vertical = 8.dp),
                )

                Text("Longueur : ${length.toInt()}", style = MaterialTheme.typography.bodyMedium)
                Slider(
                    value = length,
                    onValueChange = { length = it; regenerate() },
                    valueRange = PasswordOptions.MIN_LENGTH.toFloat()..PasswordOptions.MAX_LENGTH.toFloat(),
                )

                ToggleRow("Majuscules (A-Z)", useUpper) { useUpper = it; regenerate() }
                ToggleRow("Minuscules (a-z)", useLower) { useLower = it; regenerate() }
                ToggleRow("Chiffres (0-9)", useDigits) { useDigits = it; regenerate() }
                ToggleRow("Symboles (!@#…)", useSymbols) { useSymbols = it; regenerate() }
                ToggleRow("Éviter les caractères ambigus", avoidAmbiguous) { avoidAmbiguous = it; regenerate() }
            }
        },
        confirmButton = {
            TextButton(
                onClick = { if (generated.isNotEmpty()) onAccept(generated) },
                enabled = generated.isNotEmpty(),
            ) { Text("Utiliser") }
        },
        dismissButton = {
            Row {
                TextButton(onClick = { regenerate() }) { Text("Régénérer") }
                TextButton(onClick = onDismiss) { Text("Annuler") }
            }
        },
    )
}

@Composable
private fun ToggleRow(label: String, checked: Boolean, onCheckedChange: (Boolean) -> Unit) {
    Row(
        modifier = Modifier.fillMaxWidth(),
        verticalAlignment = Alignment.CenterVertically,
        horizontalArrangement = Arrangement.SpaceBetween,
    ) {
        Text(label, style = MaterialTheme.typography.bodyMedium)
        Switch(checked = checked, onCheckedChange = onCheckedChange)
    }
}
